const FormatInfo* format_info(int nvn_format) {
    if (nvn_format < 0 || nvn_format >= static_cast<int>(sizeof kFormats / sizeof kFormats[0])) {
        NVN_LOG("formato 0x%x sin mapear\n", nvn_format);
        return nullptr;
    }
    return &kFormats[nvn_format];
}

